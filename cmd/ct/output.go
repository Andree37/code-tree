func (g *Graph) line(i string) string {
	n, f := g.Nodes[i], g.Info[i]
	bits := []string{"[" + f.Label + "]", i, n.Title}
	if f.Unblocks > 0 && !resolved(f.State) {
		bits = append(bits, fmt.Sprintf("· unblocks %d", f.Unblocks))
	}
	if ma := modeAgent(n); ma != "" {
		bits = append(bits, "("+ma+")")
	}
	return strings.Join(bits, "  ")
}

func modeAgent(n *Node) string {
	var p []string
	for _, s := range []string{n.Mode, n.Agent} {
		if s != "" {
			p = append(p, s)
		}
	}
	return strings.Join(p, " · ")
}

func (g *Graph) printTree(h string, all bool) {
	printed := map[string]bool{}
	var walk func(i, prefix string, last, root bool)
	walk = func(i, prefix string, last, root bool) {
		conn := ""
		if !root {
			conn = "├─ "
			if last {
				conn = "└─ "
			}
		}
		if printed[i] {
			fmt.Printf("%s%s↑ %s (shown above)\n", prefix, conn, i)
			return
		}
		printed[i] = true
		mark := ""
		if root {
			mark = "◆ "
		}
		fmt.Printf("%s%s%s%s\n", prefix, conn, mark, g.line(i))
		var kids []string
		for _, k := range g.Info[i].Children {
			if all || !resolved(g.Info[k].State) {
				kids = append(kids, k)
			}
		}
		ext := ""
		if !root {
			ext = "│  "
			if last {
				ext = "   "
			}
		}
		for k, c := range kids {
			walk(c, prefix+ext, k == len(kids)-1, false)
		}
	}
	walk(h, "", true, true)
	fmt.Println()
}

// ---------------------------------------------------------------- GRAPH.md

func (g *Graph) mermaid(ids []string) string {
	alias := map[string]string{}
	for k, i := range ids {
		alias[i] = fmt.Sprintf("n%d", k)
	}
	lines := []string{"graph TD"}
	for _, i := range ids {
		t := strings.ReplaceAll(g.Nodes[i].Title, `"`, "#quot;")
		cls := strings.ReplaceAll(g.Info[i].State, "-", "")
		lines = append(lines, fmt.Sprintf(`  %s["%s<br/><i>%s</i>"]:::%s`, alias[i], t, g.Info[i].Label, cls))
	}
	for _, i := range ids {
		for _, c := range g.Info[i].Children {
			if a, ok := alias[c]; ok {
				lines = append(lines, fmt.Sprintf("  %s --> %s", alias[i], a))
			}
		}
	}
	lines = append(lines,
		"  classDef waiting stroke:#888",
		"  classDef open stroke:#888",
		"  classDef working stroke:#4a90d9,stroke-width:2px",
		"  classDef needsyou stroke:#ff6a00,stroke-width:2px",
		"  classDef ready stroke:#ff6a00,stroke-width:2px",
		"  classDef stale stroke:#d93f3f,stroke-width:2px,stroke-dasharray:4",
		"  classDef done opacity:0.5",
		"  classDef dropped opacity:0.3",
	)
	return strings.Join(lines, "\n")
}

func orDash(s []string) string {
	if len(s) == 0 {
		return "—"
	}
	return strings.Join(s, ", ")
}

func writeGraphMD(dir string) {
	g := load(dir)
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# code-tree graph\n")
	w("_Generated by `ct` at %s. Do not edit; source of truth is `.tree/nodes/*.md`. Protocol: `.tree/PROTOCOL.md`._\n", now())
	w("Edges point from a node to what it waits on. `unblocks` = unresolved nodes above it.\n")
	w("## Next\n")
	if next := g.actionable("all"); len(next) > 0 {
		w("| state | id | title | unblocks | head |")
		w("|---|---|---|---|---|")
		for _, i := range next {
			var hs []string
			for _, h := range g.headsOf(i) {
				hs = append(hs, g.Nodes[h].Title)
			}
			w("| %s | `%s` | %s | %d | %s |", g.Info[i].Label, i, g.Nodes[i].Title, g.Info[i].Unblocks, strings.Join(hs, ", "))
		}
	} else {
		w("_Nothing actionable._")
	}
	w("")
	if st := readSync(dir); st.Head != "" {
		cfg := loadConfig(dir)
		w("## Code sync\n")
		w("Last `ct sync`: `%s` in `%s` at %s.\n", short(st.Head), cfg.Raw, st.Synced)
		var stale []string
		for _, i := range g.IDs {
			if s := g.Nodes[i].Stale; len(s) > 0 {
				stale = append(stale, fmt.Sprintf("- `%s` %s — changed: %s", i, g.Nodes[i].Title, strings.Join(s, ", ")))
			}
		}
		if len(stale) > 0 {
			w("**Stale** (resolved, but their code changed since; recheck, then `ct ack` or reopen):\n")
			w("%s\n", strings.Join(stale, "\n"))
		}
		if len(st.Unmapped) > 0 {
			w("**Unmapped changes** (no node touches these; `ct touch <id> <path>` to own them):\n")
			for k, p := range st.Unmapped {
				if k == 30 {
					w("- … %d more in `.tree/sync`", len(st.Unmapped)-30)
					break
				}
				w("- `%s`", p)
			}
			w("")
		}
	}
	for _, h := range g.heads() {
		ids := g.bfs(h)
		w("## HEAD `%s` — %s · %d nodes · %s\n", h, g.Nodes[h].Title, len(ids), g.Info[h].Label)
		w("```mermaid\n%s\n```\n", g.mermaid(ids))
		var ds []string
		for _, i := range ids {
			for _, d := range g.Nodes[i].Decisions {
				ds = append(ds, fmt.Sprintf("- %s (`%s`)", d, i))
			}
		}
		if len(ds) > 0 {
			w("**Decisions** (hold for the node and everything below it):\n\n%s\n", strings.Join(ds, "\n"))
		}
		w("| id | state | title | waits on | blocks | unblocks | mode · agent | touches | outcome |")
		w("|---|---|---|---|---|---|---|---|---|")
		for _, i := range ids {
			n, f := g.Nodes[i], g.Info[i]
			w("| `%s` | %s | %s | %s | %s | %d | %s | %s | %s |", i, f.Label, n.Title, orDash(f.Children), orDash(f.Parents), f.Unblocks, modeAgent(n), strings.Join(n.Touches, ", "), n.Outcome)
		}
		w("")
	}
	if err := writeAtomic(filepath.Join(dir, "GRAPH.md"), []byte(b.String())); err != nil {
		die("%v", err)
	}
}

// ---------------------------------------------------------------- web view

func renderHTML(dir, token string) string {
	g := load(dir)
	// HTML-escaped into a hidden element: no node text can end it early or turn into markup
	data := html.EscapeString(g.dump())
	return strings.Replace(strings.Replace(graphHTML, "__TOKEN__", token, 1), "__DATA__", data, 1)
}

// actionArgs maps a page action to a ct command line. Text always comes after "--".
func actionArgs(action, id, text string) ([]string, bool) {
	if id == "" {
		return nil, false
	}
	by := []string{"--by", "human"}
	withText := func(cmd string) []string { return append(append([]string{cmd}, by...), "--", id, text) }
	withNote := func(cmd string) []string {
		args := append([]string{cmd}, by...)
		if text != "" {
			args = append(args, "--note", text)
		}
		return append(args, "--", id)
	}
	switch action {
	case "work", "run":
		return append(append([]string{action}, by...), "--", id), true
	case "answer", "decide", "note", "chat", "talk":
		if text == "" {
			return nil, false
		}
		return withText(action), true
	case "reject":
		return withText(action), true
	case "accept", "ack", "done", "drop", "open":
		return withNote(action), true
	case "add":
		if text == "" {
			return nil, false
		}
		return append(append([]string{"add"}, by...), "-b", id, "--", text), true
	}
	return nil, false
}

// runSelf runs this ct binary against the tree and returns its output.
func runSelf(tree string, args []string) (string, error) {
	exe, err := os.Executable()
	if err != nil {
		return err.Error(), err
	}
	if abs, err := filepath.Abs(tree); err == nil { // the child runs in another folder: a relative tree would point elsewhere
		tree = abs
	}
	cmd := exec.Command(exe, args...)
	cmd.Dir = filepath.Dir(tree)
	// the page and panes act as the human, and only on the exact node shown:
	// CT_EXACT_ID turns off prefix matching, so a deleted id never lands on a neighbour
	cmd.Env = append(os.Environ(), "CT_TREE="+tree, "CT_AGENT=", "CLAUDECODE=", "IC_ID=", "CT_EXACT_ID=1")
	out, err := cmd.CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

func openBrowser(url string) {
	cmd := "xdg-open"
	if runtime.GOOS == "darwin" {
		cmd = "open"
	} else if runtime.GOOS == "windows" {
		cmd = "explorer"
	}
	_ = exec.Command(cmd, url).Start()
}

